fun getAppStrings(languageCode: String): AppStrings {
    return when (languageCode.lowercase().take(2)) {
        "en" -> EnglishStrings
        "ar" -> ArabicStrings
        "ru" -> RussianStrings
        "es" -> SpanishStrings
        "fr" -> FrenchStrings
        "de" -> GermanStrings
        "ja" -> JapaneseStrings
        "zh" -> ChineseStrings
        "id", "in" -> IndonesianStrings
        else -> EnglishStrings
    }
}

